// Fullwidth is stored in the cell following a fullwidth glyph.
const Fullwidth rune = 0x000ffffe

// UTF8ToUTF32 decodes UTF-8 into runes. Invalid bytes become
// utf8.RuneError and consume one byte.
func UTF8ToUTF32(s string) []rune {
	out := make([]rune, 0, len(s))
	for len(s) > 0 {
		r, size := utf8.DecodeRuneInString(s)
		if size == 0 {
			break
		}
		out = append(out, r)
		s = s[size:]
	}
	return out
}

// UTF32ToUTF8 encodes runes as UTF-8. Invalid runes become utf8.RuneError.
func UTF32ToUTF8(rs []rune) string {
	var b strings.Builder
	b.Grow(len(rs))
	for _, r := range rs {
		if !utf8.ValidRune(r) {
			r = utf8.RuneError
		}
		b.WriteRune(r)
	}
	return b.String()
}

